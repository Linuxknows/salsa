const O_NOFOLLOW: i32 = 0x20000;
const O_CLOEXEC: i32 = 0x80000;

fn is_valid_ident(sym: &str) -> bool {
    let bytes = sym.as_bytes();
    if bytes.is_empty() {
        return false;
    }
    let first = bytes[0];
    if !(first.is_ascii_alphabetic() || first == b'_') {
        return false;
    }
    bytes[1..]
        .iter()
        .all(|&b| b.is_ascii_alphanumeric() || b == b'_')
}

pub fn validate_stubs(stubs: &[String]) -> Result<(), String> {
    for sym in stubs {
        if !is_valid_ident(sym) || sym.starts_with('_') {
            return Err(format!("Invalid or unsafe symbol identifier: {sym:?}"));
        }
    }
    Ok(())
}

fn get_defined_symbols(proxy_obj: &str) -> Result<HashSet<String>, String> {
    let out = Command::new("nm")
        .args(["-g", "--defined-only", proxy_obj])
        .output()
        .map_err(|e| format!("failed to run nm -g on {proxy_obj}: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "nm -g failed on {proxy_obj}: {}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    let stdout = String::from_utf8_lossy(&out.stdout);
    let mut syms = HashSet::new();
    for line in stdout.lines() {
        let parts: Vec<&str> = line.split_whitespace().collect();
        if parts.len() >= 3 && matches!(parts[1], "T" | "W" | "D" | "B" | "R") {
            let name = parts[2].split('@').next().unwrap_or("");
            if is_valid_ident(name) {
                syms.insert(name.to_string());
            }
        }
    }
    Ok(syms)
}

fn get_host_pulse_functions(host_libpulse: &str) -> Result<Vec<String>, String> {
    let out = Command::new("nm")
        .args(["-D", "--defined-only", host_libpulse])
        .output()
        .map_err(|e| format!("failed to run nm -D on {host_libpulse}: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "nm -D failed on {host_libpulse}: {}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    let stdout = String::from_utf8_lossy(&out.stdout);
    let mut seen = HashSet::new();
    let mut funcs = Vec::new();
    for line in stdout.lines() {
        let parts: Vec<&str> = line.split_whitespace().collect();
        if parts.len() < 3 {
            continue;
        }
        let sym_type = parts[1];
        let sym_name = parts[2].split('@').next().unwrap_or("");
        if sym_type != "T" && sym_type != "W" {
            continue;
        }
        if sym_name.is_empty() || sym_name.starts_with('_') || seen.contains(sym_name) {
            continue;
        }
        if !is_valid_ident(sym_name) {
            continue;
        }
        seen.insert(sym_name.to_string());
        funcs.push(sym_name.to_string());
    }
    funcs.sort();
    Ok(funcs)
}

pub fn emit_x86_64(stubs: &[String]) -> Result<String, String> {
    validate_stubs(stubs)?;
    let arr_sz = (stubs.len() + 1) * 8;
    let mut lines = vec![
        "/* Auto-generated by salsa-gen-pa-proxy — do not edit */".to_string(),
        ".bss".to_string(),
        "    .align 8".to_string(),
        "    .globl salsa_pa_stub_targets".to_string(),
        "    .hidden salsa_pa_stub_targets".to_string(),
        "    .type salsa_pa_stub_targets, @object".to_string(),
        format!("    .size salsa_pa_stub_targets, {arr_sz}"),
        "salsa_pa_stub_targets:".to_string(),
        format!("    .zero {arr_sz}"),
        String::new(),
        r#".section .rodata.str1.1,"aMS",@progbits,1"#.to_string(),
    ];
    for (idx, sym) in stubs.iter().enumerate() {
        lines.push(format!(r#".Lpa_name_{idx}: .string "{sym}""#));
    }

    lines.extend([
        String::new(),
        r#".section .data.rel.ro,"aw",@progbits"#.to_string(),
        "    .align 8".to_string(),
        "    .globl salsa_pa_stub_names".to_string(),
        "    .hidden salsa_pa_stub_names".to_string(),
        "    .type salsa_pa_stub_names, @object".to_string(),
        format!("    .size salsa_pa_stub_names, {arr_sz}"),
        "salsa_pa_stub_names:".to_string(),
    ]);
    for idx in 0..stubs.len() {
        lines.push(format!("    .quad .Lpa_name_{idx}"));
    }
    lines.push("    .quad 0".to_string());

    lines.extend(
        [
            "",
            ".text",
            "    .align 16",
            "    .local salsa_pa_proxy_save_and_init",
            "    .type salsa_pa_proxy_save_and_init, @function",
            "salsa_pa_proxy_save_and_init:",
            "    pushq %rax",
            "    pushq %rdi",
            "    pushq %rsi",
            "    pushq %rdx",
            "    pushq %rcx",
            "    pushq %r8",
            "    pushq %r9",
            "    subq $136, %rsp",
            "    movdqu %xmm0, 0(%rsp)",
            "    movdqu %xmm1, 16(%rsp)",
            "    movdqu %xmm2, 32(%rsp)",
            "    movdqu %xmm3, 48(%rsp)",
            "    movdqu %xmm4, 64(%rsp)",
            "    movdqu %xmm5, 80(%rsp)",
            "    movdqu %xmm6, 96(%rsp)",
            "    movdqu %xmm7, 112(%rsp)",
            "    call salsa_pa_proxy_ensure_stubs@PLT",
            "    movdqu 112(%rsp), %xmm7",
            "    movdqu 96(%rsp), %xmm6",
            "    movdqu 80(%rsp), %xmm5",
            "    movdqu 64(%rsp), %xmm4",
            "    movdqu 48(%rsp), %xmm3",
            "    movdqu 32(%rsp), %xmm2",
            "    movdqu 16(%rsp), %xmm1",
            "    movdqu 0(%rsp), %xmm0",
            "    addq $136, %rsp",
            "    popq %r9",
            "    popq %r8",
            "    popq %rcx",
            "    popq %rdx",
            "    popq %rsi",
            "    popq %rdi",
            "    popq %rax",
            "    ret",
            "    .size salsa_pa_proxy_save_and_init, .-salsa_pa_proxy_save_and_init",
            "",
        ]
        .into_iter()
        .map(String::from),
    );

    for (idx, sym) in stubs.iter().enumerate() {
        let off = idx * 8;
        lines.extend([
            "    .align 16".to_string(),
            format!("    .globl {sym}"),
            format!("    .type {sym}, @function"),
            format!("{sym}:"),
            format!("    movq salsa_pa_stub_targets+{off}(%rip), %r11"),
            "    testq %r11, %r11".to_string(),
            "    jz 1f".to_string(),
            "    jmp *%r11".to_string(),
            "1:".to_string(),
            "    call salsa_pa_proxy_save_and_init".to_string(),
            format!("    movq salsa_pa_stub_targets+{off}(%rip), %r11"),
            "    testq %r11, %r11".to_string(),
            "    jz 2f".to_string(),
            "    jmp *%r11".to_string(),
            "2:".to_string(),
            "    xorl %eax, %eax".to_string(),
            "    ret".to_string(),
            format!("    .size {sym}, .-{sym}"),
        ]);
    }

    lines.extend([
        String::new(),
        r#".section .note.GNU-stack,"",@progbits"#.to_string(),
        String::new(),
    ]);
    Ok(lines.join("\n"))
}

pub fn emit_aarch64(stubs: &[String]) -> Result<String, String> {
    validate_stubs(stubs)?;
    let arr_sz = (stubs.len() + 1) * 8;
    let mut lines = vec![
        "/* Auto-generated by salsa-gen-pa-proxy — do not edit */".to_string(),
        ".bss".to_string(),
        "    .align 3".to_string(),
        "    .globl salsa_pa_stub_targets".to_string(),
        "    .hidden salsa_pa_stub_targets".to_string(),
        "    .type salsa_pa_stub_targets, %object".to_string(),
        format!("    .size salsa_pa_stub_targets, {arr_sz}"),
        "salsa_pa_stub_targets:".to_string(),
        format!("    .zero {arr_sz}"),
        String::new(),
        r#".section .rodata.str1.1,"aMS",%progbits,1"#.to_string(),
    ];
    for (idx, sym) in stubs.iter().enumerate() {
        lines.push(format!(r#".Lpa_name_{idx}: .string "{sym}""#));
    }

    lines.extend([
        String::new(),
        r#".section .data.rel.ro,"aw",%progbits"#.to_string(),
        "    .align 3".to_string(),
        "    .globl salsa_pa_stub_names".to_string(),
        "    .hidden salsa_pa_stub_names".to_string(),
        "    .type salsa_pa_stub_names, %object".to_string(),
        format!("    .size salsa_pa_stub_names, {arr_sz}"),
        "salsa_pa_stub_names:".to_string(),
    ]);
    for idx in 0..stubs.len() {
        lines.push(format!("    .xword .Lpa_name_{idx}"));
    }
    lines.push("    .xword 0".to_string());

    lines.extend(
        [
            "",
            ".text",
            "    .align 4",
            "    .local salsa_pa_proxy_save_and_init",
            "    .type salsa_pa_proxy_save_and_init, %function",
            "salsa_pa_proxy_save_and_init:",
            "    stp x29, x30, [sp, #-240]!",
            "    mov x29, sp",
            "    stp x0, x1, [sp, #16]",
            "    stp x2, x3, [sp, #32]",
            "    stp x4, x5, [sp, #48]",
            "    stp x6, x7, [sp, #64]",
            "    str x8, [sp, #80]",
            "    stp q0, q1, [sp, #96]",
            "    stp q2, q3, [sp, #128]",
            "    stp q4, q5, [sp, #160]",
            "    stp q6, q7, [sp, #192]",
            "    bl salsa_pa_proxy_ensure_stubs",
            "    ldp q6, q7, [sp, #192]",
            "    ldp q4, q5, [sp, #160]",
            "    ldp q2, q3, [sp, #128]",
            "    ldp q0, q1, [sp, #96]",
            "    ldr x8, [sp, #80]",
            "    ldp x6, x7, [sp, #64]",
            "    ldp x4, x5, [sp, #48]",
            "    ldp x2, x3, [sp, #32]",
            "    ldp x0, x1, [sp, #16]",
            "    ldp x29, x30, [sp], #240",
            "    ret",
            "    .size salsa_pa_proxy_save_and_init, .-salsa_pa_proxy_save_and_init",
            "",
        ]
        .into_iter()
        .map(String::from),
    );

    for (idx, sym) in stubs.iter().enumerate() {
        let off = idx * 8;
        lines.extend([
            "    .align 4".to_string(),
            format!("    .globl {sym}"),
            format!("    .type {sym}, %function"),
            format!("{sym}:"),
            format!("    adrp x16, salsa_pa_stub_targets+{off}"),
            format!("    ldr x16, [x16, #:lo12:salsa_pa_stub_targets+{off}]"),
            "    cbz x16, 1f".to_string(),
            "    br x16".to_string(),
            "1:".to_string(),
            "    stp x29, x30, [sp, #-16]!".to_string(),
            "    bl salsa_pa_proxy_save_and_init".to_string(),
            "    ldp x29, x30, [sp], #16".to_string(),
            format!("    adrp x16, salsa_pa_stub_targets+{off}"),
            format!("    ldr x16, [x16, #:lo12:salsa_pa_stub_targets+{off}]"),
            "    cbz x16, 2f".to_string(),
            "    br x16".to_string(),
            "2:".to_string(),
            "    mov x0, #0".to_string(),
            "    ret".to_string(),
            format!("    .size {sym}, .-{sym}"),
        ]);
    }

    lines.extend([
        String::new(),
        r#".section .note.GNU-stack,"",%progbits"#.to_string(),
        String::new(),
    ]);
    Ok(lines.join("\n"))
}

