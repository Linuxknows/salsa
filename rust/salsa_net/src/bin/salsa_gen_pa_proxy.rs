fn self_test() -> Result<(), String> {
    for bad in ["pa_bad;id", "pa_evil\njmp", "../etc/passwd", "_private"] {
        if validate_stubs(&[bad.to_string()]).is_ok() {
            return Err(format!("accepted unsafe identifier: {bad:?}"));
        }
    }
    let good = vec!["pa_context_new".to_string(), "pa_stream_write".to_string()];
    validate_stubs(&good)?;
    let x64 = emit_x86_64(&good)?;
    if !x64.contains("salsa_pa_stub_targets") || !x64.contains(".globl pa_context_new") {
        return Err("emit_x86_64 output malformed".to_string());
    }
    let arm = emit_aarch64(&good)?;
    if !arm.contains("adrp x16, salsa_pa_stub_targets") {
        return Err("emit_aarch64 output malformed".to_string());
    }
    let x86 = emit_i386(&good)?;
    if !x86.contains("@GOTOFF(%ecx)") {
        return Err("emit_i386 output malformed".to_string());
    }
    Ok(())
}

fn run() -> Result<(), String> {
    salsa_wire::unix_sys::reset_sigpipe_default();
    let mut arch = env::consts::ARCH.to_string();
    let mut positional: Vec<String> = Vec::new();
    let mut args = env::args().skip(1);
    while let Some(arg) = args.next() {
        if arg == "--self-test" {
            self_test()?;
            println!("salsa-gen-pa-proxy self-test passed");
            return Ok(());
        } else if arg == "--arch" {
            arch = args
                .next()
                .ok_or_else(|| "--arch requires a value".to_string())?;
        } else if let Some(val) = arg.strip_prefix("--arch=") {
            arch = val.to_string();
        } else if arg == "-h" || arg == "--help" {
            println!("Usage: salsa-gen-pa-proxy [--arch ARCH] <host_libpulse> <proxy_obj_or_a> <out_stub>");
            println!("       salsa-gen-pa-proxy --self-test");
            return Ok(());
        } else {
            positional.push(arg);
        }
    }

    if positional.len() != 3 {
        return Err(
            "Expected <host_libpulse> <proxy_obj_or_a> <out_stub> (or --self-test)".to_string(),
        );
    }
    let host_libpulse = &positional[0];
    let proxy_obj = &positional[1];
    let out_stub = &positional[2];

    let defined = get_defined_symbols(proxy_obj)?;
    let host_funcs = get_host_pulse_functions(host_libpulse)?;
    let stubs: Vec<String> = host_funcs
        .into_iter()
        .filter(|s| !defined.contains(s))
        .collect();

    let arch_lower = arch.to_ascii_lowercase();
    let asm = match arch_lower.as_str() {
        "x86_64" | "amd64" => emit_x86_64(&stubs)?,
        "aarch64" | "arm64" => emit_aarch64(&stubs)?,
        "i386" | "i686" | "x86" => emit_i386(&stubs)?,
        other => {
            return Err(format!(
                "Unsupported architecture for PA proxy stubs: {other}"
            ))
        }
    };

    let tmp = format!("{out_stub}.tmp.{}", std::process::id());
    let _ = fs::remove_file(&tmp);
    let write_res = OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o644)
        .custom_flags(O_NOFOLLOW | O_CLOEXEC)
        .open(&tmp)
        .and_then(|mut f| f.write_all(asm.as_bytes()));
    if let Err(e) = write_res {
        let _ = fs::remove_file(&tmp);
        return Err(format!("failed writing {tmp}: {e}"));
    }
    if let Err(e) = fs::rename(&tmp, out_stub) {
        let _ = fs::remove_file(&tmp);
        return Err(format!("failed renaming {tmp} -> {out_stub}: {e}"));
    }
    println!(
        "Generated {} libpulse forwarding stubs ({arch_lower}) -> {out_stub}",
        stubs.len()
    );
    Ok(())
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("salsa-gen-pa-proxy: {e}");
            ExitCode::FAILURE
        }
    }
}

